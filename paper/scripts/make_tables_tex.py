METHOD = "DistilSCD"


def tab(name):
    return pd.read_csv(TABLES / f"{name}.csv")


# ----------------------------------------------------------------------------- formatting
def n(x, d=2, sign=False):
    """Number with d decimals; true minus sign; '--' for missing."""
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--"
    s = f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
    return s.replace("-", "$-$")


def pm(m, sd, d=2):
    return f"{n(m, d)}\\,$\\pm$\\,{n(sd, d)}"


def ci(m, lo, hi, d=2, sign=True):
    return f"{n(m, d, sign)} [{n(lo, d)}, {n(hi, d)}]"


def pval(p):
    if p is None or (isinstance(p, float) and np.isnan(p)):
        return "--"
    if p < 1e-3:   # includes p stored as 0.0 after rounding to 4 decimals in the CSV
        return "$<$0.001"
    return f"{p:.3f}" if p < 0.01 else f"{p:.2f}"


def thousands(k):
    return f"{int(k):,}".replace(",", "\\,")


def write(name, body):
    path = OUT / f"{name}.tex"
    path.write_text("% generated by paper/scripts/make_tables_tex.py from paper/tables/*.csv -- do not edit\n"
                    + body.strip() + "\n")
    print(path.relative_to(ROOT))
    return path


def float_env(caption, label, colspec, header, rows, wide=False, notes=None, size="\\footnotesize", sep=4):
    env = "table*" if wide else "table"
    lines = [f"\\begin{{{env}}}[!t]", "\\centering", size, f"\\caption{{{caption}}}", f"\\label{{{label}}}",
             f"\\setlength{{\\tabcolsep}}{{{sep}pt}}", f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", header + " \\\\",
             "\\midrule"]
    for r in rows:
        lines.append(r if r.strip() in RULES else r + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    if notes:
        width = "\\textwidth" if wide else "\\columnwidth"
        lines += [f"\\par\\smallskip\\parbox{{{width}}}{{\\scriptsize {notes}}}"]
    lines.append(f"\\end{{{env}}}")
    return "\n".join(lines)


RULES = {"\\midrule", "\\addlinespace"}


def pexpr(p):
    """'$p$ = 0.13' or '$p < 0.001$'."""
    v = pval(p)
    return "$p < 0.001$" if v.startswith("$<$") else f"$p$ = {v}"


def count(path):
    return sum(1 for l in Path(path).read_text().splitlines() if l.strip())


