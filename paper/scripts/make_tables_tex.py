def table4():
    eff = tab("efficiency")
    tc = tab("training_cost")
    rows = []
    for _, r in eff.iterrows():
        q = r.quantity.replace("GMACs / pair, aten counter", "GMACs / pair (aten counter)") \
                      .replace("GMACs / pair, fvcore", "GMACs / pair (fvcore)")
        q = q.replace("latency", "Latency").replace("peak memory", "Peak memory")
        d = 2 if "GMACs" in q or "memory" in q else (1 if "Latency" in q else 1)
        ratio = (n(r.ratio, 1) + "$\\times$") if not np.isnan(r.ratio) else "--"
        rows.append(f"{q} & {n(r.student, d) if not np.isnan(r.student) else '--'} & "
                    f"{n(r.teacher, d) if not np.isnan(r.teacher) else '--'} & {ratio}")
    body1 = float_env(f"Inference cost of {METHOD} and its ViT-G teacher on the same A100 GPU.",
                      "tab:efficiency", "lrrr", f"Quantity & {METHOD} & Teacher & Ratio", rows,
                      notes="Same job and GPU for both models; 512$\\times$512 pairs; median latency; "
                            "b8 / b1: batch of 8 / 1 pair(s). The teacher's fvcore count failed (JIT tracing of "
                            "bicubic interpolation). Both counters ignore custom CUDA operators.")
    # training cost
    label = {"kdchg-l8": "change KD", "kdlogits": f"{METHOD} (output KD)", "witness": "no KD",
             "kdsem-l8-t2-all": f"{METHOD} (output KD)", "kdfeat-s12-l1": "+ feat. KD 1/8, 1/16; 1",
             "kdfeat-s123-l1": "+ feat. KD 1/8--1/32; 1",
             "kdfeat-s12-l4": "+ feat. KD 1/8, 1/16; 4"}
    rows2, protos = [], {}
    for _, r in tc.iterrows():
        setting, tag = r.setting.rsplit(") ", 1)
        proto = {"confirm": "confirm.", "screen": "screen."}[setting.split(" (")[0]]
        protos[proto] = setting.split("(")[1]
        rows2.append(f"{proto} & {label[tag]} & {int(r.n_runs)} & "
                     f"{n(r.hours_per_run, 2)} & {n(r.train_s_per_epoch, 1)} & {n(r.peak_train_gb, 2)}")
    pnote = "; ".join(f"{k}: {v.replace('test val', 'test set as validation')}" for k, v in protos.items())
    body2 = float_env("Training cost per run (120 epochs, one A100).", "tab:trainingcost", "@{}llrrrr@{}",
                      "Prot. & Arm & Runs & h/run & s/epoch & GB", rows2, sep=3,
                      notes=f"Pairs used ({pnote}). GB: peak training memory. From the run timing logs. "
                            "Output KD reads the offline logit cache and adds no measurable training time; "
                            "feature KD runs the teacher online.")
    # one float (Table IV) holding both blocks, so that table numbering follows the brief (I-VII)
    def inner(body):
        lines = body.splitlines()
        i0 = next(i for i, l in enumerate(lines) if l.startswith("\\setlength"))
        i1 = next(i for i, l in enumerate(lines) if l.startswith("\\end{tabular}"))
        note = next((l for l in lines[i1 + 1:] if l.startswith("\\par")), "")
        return "\n".join(lines[i0:i1 + 1]), note
    t1, n1 = inner(body1)
    t2, n2 = inner(body2)
    body = "\n".join([
        "\\begin{table}[!t]", "\\centering", "\\footnotesize",
        f"\\caption{{Efficiency of {METHOD} and its ViT-G teacher on one A100 GPU: (a) inference, "
        "(b) training cost per run (120 epochs).}", "\\label{tab:efficiency}",
        "\\textit{(a) Inference}\\par\\smallskip", t1, n1, "\\par\\medskip",
        "\\textit{(b) Training}\\par\\smallskip", t2, n2, "\\end{table}"])
    return write("table4_efficiency", body)


