"""LaTeX tables of the DistilSCD paper (IEEE JSTARS, booktabs) generated from paper/tables/*.csv.

    python paper/scripts/make_tables_tex.py

Every value is formatted from a CSV (or, for Table I, counted from the released split files
in splits/); nothing is typed by hand. Output: paper/tables_tex/table{1..7}_*.tex, each a
complete `table`/`table*` float to \\input{} in the manuscript. Requires \\usepackage{booktabs}
(and \\usepackage{multirow} is NOT needed). SeK, Fscd, mIoU in percentage points.
"""
from __future__ import annotations

